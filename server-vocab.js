function fetchJson(url) {
    return new Promise((resolve) => {
        https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
            let data = '';
            res.on('data', chunk => data += chunk);
            res.on('end', () => {
                try { resolve(JSON.parse(data)); } catch (e) { resolve(null); }
            });
        }).on('error', () => resolve(null));
    });
}

function detectCategory(word, pos, def, trans) {
    const combined = `${word} ${def || ''} ${trans || ''}`.toLowerCase();
    if (/business|job|work|office|career|finance|project|meeting|company|professional|management|sales/i.test(combined)) return 'Work';
    if (/study|academic|exam|research|science|theory|intellectual|thesis|university|school|ielts/i.test(combined)) return 'Academic';
    if (/feel|emotion|happy|sad|calm|mood|courage|mental|fear|trait|attitude|heart|mind/i.test(combined)) return 'Emotion';
    if (/tech|software|computer|digital|code|internet|network|app|ai|data|device/i.test(combined)) return 'Technology';
    if (pos === 'idiom' || /slang|informal|street|casual/i.test(combined)) return 'Slang';
    return 'Daily';
}

function generateExampleTemplate(word, pos, trans) {
    const w = word.trim();
    if (pos === 'verb') {
        return {
            en: `She decided to ${w} to achieve her goals.`,
            id: `Dia memutuskan untuk ${trans || w} demi mencapai tujuannya.`
        };
    } else if (pos === 'adjective') {
        return {
            en: `His approach to problem-solving was remarkably ${w}.`,
            id: `Pendekatannya dalam memecahkan masalah sangat ${trans || w}.`
        };
    } else if (pos === 'adverb') {
        return {
            en: `They handled the entire situation ${w}.`,
            id: `Mereka menangani seluruh situasi tersebut secara ${trans || w}.`
        };
    } else if (pos === 'idiom' || pos === 'phrasal_verb') {
        return {
            en: `Remember to ${w} whenever you encounter difficulties.`,
            id: `Ingatlah untuk ${trans || w} setiap kali kamu menemui kesulitan.`
        };
    }
    // Noun / default
    return {
        en: `Understanding the concept of ${w} made a big difference.`,
        id: `Memahami konsep ${trans || w} membawa perbedaan yang besar.`
    };
}

const server = http.createServer((req, res) => {
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

    if (req.method === 'OPTIONS') {
        res.writeHead(204);
        res.end();
        return;
    }

    const parsedUrl = new URL(req.url, `http://localhost:${PORT}`);
    const pathname = decodeURIComponent(parsedUrl.pathname);

    // ========================================================
    // API: ENRICH WORD AUTOMATICALLY (/api/enrich-word)
    // Cukup kirim kata bahasa Inggris, sistem mengisi semuanya!
    // ========================================================
    if (pathname === '/api/enrich-word') {
        const rawWord = parsedUrl.searchParams.get('word');
        if (!rawWord || !rawWord.trim()) {
            res.writeHead(400, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({ error: 'Parameter word wajib diisi' }));
            return;
        }

        const word = rawWord.trim();
        const lowerWord = word.toLowerCase();

        (async () => {
            // 0. Cek Kamus Terverifikasi (Akurasi 100% Instan)
            if (CURATED_VOCAB_DB[lowerWord]) {
                const curated = CURATED_VOCAB_DB[lowerWord];
                res.writeHead(200, { 'Content-Type': 'application/json' });
                res.end(JSON.stringify({
                    success: true,
                    word,
                    translation: curated.translation,
                    pos: curated.pos,
                    category: curated.category || 'Daily',
                    phonetic: curated.phonetic || '',
                    example: curated.example,
                    exampleTranslation: curated.exampleTrans,
                    mnemonic: curated.mnemonic,
                    level: curated.level || 'A2',
                    alternatives: []
                }));
                return;
            }

            // 1. Check if exact idiom exists
            if (IDIOMS_DB[lowerWord]) {
                const idm = IDIOMS_DB[lowerWord];
                res.writeHead(200, { 'Content-Type': 'application/json' });
                res.end(JSON.stringify({
                    success: true,
                    word,
                    translation: idm.natural,
                    pos: 'idiom',
                    category: 'Daily',
                    phonetic: '',
                    example: idm.example || `It is always useful to ${word}.`,
                    exampleTranslation: idm.exampleTrans || `Selalu berguna untuk ${idm.natural}.`,
                    mnemonic: idm.explanation || `Makna kiasan: ${idm.natural}`,
                    level: 'B2',
                    alternatives: idm.alternatives || []
                }));
                return;
            }

            // 2. Query Dictionary API and Translation API in parallel
            const dictUrl = `https://api.dictionaryapi.dev/api/v2/entries/en/${encodeURIComponent(lowerWord)}`;
            const transUrl = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(word)}&langpair=en|id`;

            const [dictData, transData] = await Promise.all([fetchJson(dictUrl), fetchJson(transUrl)]);

            let rawTrans = transData?.responseData?.translatedText || '';
            rawTrans = rawTrans.replace(/[.\s]+$/, '').trim();

            // Cek jika hasil MyMemory rusak (sama dengan kata asli, 'Premium' untuk promote, 'pasti' untuk ever, dsb)
            const isBadRawTrans = !rawTrans || 
                rawTrans.toLowerCase() === word.toLowerCase() || 
                rawTrans.includes('MYMEMORY WARNING') ||
                (lowerWord === 'promote' && rawTrans.toLowerCase() === 'premium') ||
                (lowerWord === 'ever' && rawTrans.toLowerCase() === 'pasti');

            if (isBadRawTrans && transData?.matches && Array.isArray(transData.matches)) {
                for (const m of transData.matches) {
                    if (m.translation) {
                        const cleanM = m.translation.replace(/[.\s]+$/, '').trim();
                        if (cleanM.toLowerCase() !== word.toLowerCase() && 
                            cleanM.toLowerCase() !== 'premium' && 
                            cleanM.toLowerCase() !== 'pasti' &&
                            !cleanM.includes('MYMEMORY WARNING') &&
                            cleanM.length > 1) {
                            rawTrans = cleanM;
                            break;
                        }
                    }
                }
            }

            if (!rawTrans || rawTrans.toLowerCase() === word.toLowerCase()) {
                if (CURATED_VOCAB_DB[lowerWord]) {
                    rawTrans = CURATED_VOCAB_DB[lowerWord].translation;
                } else {
                    rawTrans = word;
                }
            }

            // Polish stiff machine translation
            STIFF_PATTERNS.forEach(p => {
                if (p.regex.test(rawTrans)) rawTrans = rawTrans.replace(p.regex, p.replace);
            });

            let pos = 'noun';
            let phonetic = '';
            let def = '';
            let example = '';

            if (Array.isArray(dictData) && dictData[0]) {
                const entry = dictData[0];
                phonetic = entry.phonetic || entry.phonetics?.find(p => p.text)?.text || '';
                if (entry.meanings && entry.meanings.length > 0) {
                    const availablePos = (entry.meanings || []).map(m => m.partOfSpeech);
                if (/ful$|able$|ive$|ous$|ic$|less$|ish$/i.test(word) && availablePos.includes('adjective')) {
                    pos = 'adjective';
                } else if (/^(ever|never|always|often|sometimes|seldom|rarely|already|yet|still|soon|finally|suddenly|probably|definitely|clearly|especially|actually)$/i.test(word) || (word.endsWith('ly') && availablePos.includes('adverb'))) {
                    pos = 'adverb';
                } else if (/(tion|sion|ment|ness|ity|ship|ance|ence)$/i.test(word) && availablePos.includes('noun')) {
                    pos = 'noun';
                } else if (/(ize|ise|ate|ify)$/i.test(word) && availablePos.includes('verb')) {
                    pos = 'verb';
                } else if (availablePos.includes('adjective') && !availablePos.includes('noun')) {
                    pos = 'adjective';
                } else if (availablePos.includes('verb') && !availablePos.includes('noun')) {
                    pos = 'verb';
                } else {
                    pos = availablePos[0] || 'noun';
                }

                // Cari definisi yang cocok dengan pos
                const matchedMeaning = (entry.meanings || []).find(m => m.partOfSpeech === pos) || entry.meanings?.[0];
                if (matchedMeaning) {
                    const defObj = matchedMeaning.definitions?.find(d => d.example) || matchedMeaning.definitions?.[0];
                    if (defObj) {
                        def = defObj.definition || '';
                        example = defObj.example || '';
                    }
                }
                    const defObj = entry.meanings[0].definitions?.[0];
                    if (defObj) {
                        def = defObj.definition || '';
                        example = defObj.example || '';
                    }
                }
            }

            // If word has spaces and detected as noun, categorize as phrasal_verb or idiom
            if (word.includes(' ') && pos === 'noun') {
                pos = 'phrasal_verb';
            }

            // Detect category automatically
            const category = detectCategory(word, pos, def, rawTrans);

            // Generate example if missing
            let exampleSentence = example;
            let exampleTrans = '';

            if (exampleSentence) {
                // Auto translate the dictionary example
                const exTransUrl = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(exampleSentence)}&langpair=en|id`;
                const exTransData = await fetchJson(exTransUrl);
                exampleTrans = exTransData?.responseData?.translatedText || '';
            } else {
                const generated = generateExampleTemplate(word, pos, rawTrans);
                exampleSentence = generated.en;
                exampleTrans = generated.id;
            }

            // Generate helpful mnemonic / memory hook
            let mnemonic = '';
            if (pos === 'idiom' || pos === 'phrasal_verb') {
                mnemonic = `Gunakan dalam percakapan: ${word} = ${rawTrans}.`;
            } else {
                mnemonic = `Kunci memori: Ingat kata '${word}' (${pos}) dalam kalimat "${exampleSentence}" agar cepat hafal.`;
            }

            res.writeHead(200, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({
                success: true,
                word,
                translation: rawTrans,
                pos,
                category,
                phonetic,
                example: exampleSentence,
                exampleTranslation: exampleTrans,
                mnemonic,
                level: 'B1'
            }));
        })().catch(err => {
            res.writeHead(500, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({ error: err.message }));
        });
        return;
    }

    // ==========================================
    // API: SMART NATURAL TRANSLATE (/api/translate)
    // ==========================================
    if (pathname === '/api/translate') {
        const text = parsedUrl.searchParams.get('q');
        const from = parsedUrl.searchParams.get('from') || 'en';
        const to = parsedUrl.searchParams.get('to') || 'id';
        const tone = parsedUrl.searchParams.get('tone') || 'natural';

        if (!text) {
            res.writeHead(400, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({ error: 'Parameter text (q) wajib diisi' }));
            return;
        }

        const lowerTrimmed = text.trim().toLowerCase();
        if (from === 'en' && IDIOMS_DB[lowerTrimmed]) {
            const idm = IDIOMS_DB[lowerTrimmed];
            res.writeHead(200, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({
                success: true,
                translation: idm.natural,
                originalTranslation: idm.literal,
                detectedIdiom: {
                    idiom: lowerTrimmed,
                    natural: idm.natural,
                    literal: idm.literal,
                    explanation: idm.explanation
                },
                stiffnessFixed: true,
                alternatives: idm.alternatives || [],
                tone
            }));
            return;
        }

        const apiUrl = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(text)}&langpair=${from}|${to}`;
        https.get(apiUrl, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (apiRes) => {
            let data = '';
            apiRes.on('data', chunk => data += chunk);
            apiRes.on('end', () => {
                try {
                    const json = JSON.parse(data);
                    let rawTrans = json.responseData ? json.responseData.translatedText : '';
                    let stiffnessFixed = false;
                    let detectedIdiom = null;
                    let alternatives = [];

                    if (from === 'en') {
                        for (const [key, idmData] of Object.entries(IDIOMS_DB)) {
                            if (lowerTrimmed.includes(key)) {
                                detectedIdiom = {
                                    idiom: key,
                                    natural: idmData.natural,
                                    literal: idmData.literal,
                                    explanation: idmData.explanation
                                };
                                alternatives = idmData.alternatives || [];
                                break;
                            }
                        }

                        STIFF_PATTERNS.forEach(item => {
                            if (item.regex.test(rawTrans)) {
                                rawTrans = rawTrans.replace(item.regex, item.replace);
                                stiffnessFixed = true;
                            }
                        });
                    }

                    if (json.matches && Array.isArray(json.matches)) {
                        json.matches.forEach(m => {
                            if (m.translation && m.translation.trim() !== rawTrans.trim() && !alternatives.includes(m.translation.trim())) {
                                alternatives.push(m.translation.trim());
                            }
                        });
                    }

                    res.writeHead(200, { 'Content-Type': 'application/json' });
                    res.end(JSON.stringify({
                        success: true,
                        translation: rawTrans,
                        stiffnessFixed,
                        detectedIdiom,
                        alternatives: alternatives.slice(0, 4),
                        tone
                    }));
                } catch (e) {
                    res.writeHead(500, { 'Content-Type': 'application/json' });
                    res.end(JSON.stringify({ error: 'Gagal memproses respons translasi' }));
                }
            });
        }).on('error', (err) => {
            res.writeHead(502, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({ error: 'Koneksi ke layanan translasi gagal', details: err.message }));
        });
        return;
    }

    // ==========================================
    // API: DICTIONARY PROXY (/api/dictionary)
    // ==========================================
    if (pathname === '/api/dictionary') {
        const word = parsedUrl.searchParams.get('word');
        if (!word) {
            res.writeHead(400, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({ error: 'Parameter word wajib diisi' }));
            return;
        }

        const dictUrl = `https://api.dictionaryapi.dev/api/v2/entries/en/${encodeURIComponent(word.trim().toLowerCase())}`;
        https.get(dictUrl, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (dictRes) => {
            let data = '';
            dictRes.on('data', chunk => data += chunk);
            dictRes.on('end', () => {
                try {
                    const json = JSON.parse(data);
                    res.writeHead(dictRes.statusCode || 200, { 'Content-Type': 'application/json' });
                    res.end(JSON.stringify(json));
                } catch (e) {
                    res.writeHead(500, { 'Content-Type': 'application/json' });
                    res.end(JSON.stringify({ error: 'Gagal memproses kamus' }));
                }
            });
        }).on('error', (err) => {
            res.writeHead(502, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({ error: 'Koneksi ke kamus gagal', details: err.message }));
        });
        return;
    }

    // Route root to main english learning system HTML
    if (pathname === '/' || pathname === '/index.html' || pathname === '/vocab') {
        fs.readFile(MAIN_FILE, (err, data) => {
            if (err) {
                res.writeHead(500, { 'Content-Type': 'text/plain; charset=utf-8' });
                res.end('Error loading english-learning-system.html');
                return;
            }
            res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
            res.end(data);
        });
        return;
    }

    // Serve other static files in the directory if requested
    const filePath = path.join(BASE_DIR, pathname);

    if (!filePath.startsWith(BASE_DIR)) {
        res.writeHead(403, { 'Content-Type': 'text/plain' });
        res.end('Forbidden');
        return;
    }

    fs.stat(filePath, (err, stats) => {
        if (err || !stats.isFile()) {
            fs.readFile(MAIN_FILE, (fallbackErr, data) => {
                if (fallbackErr) {
                    res.writeHead(404, { 'Content-Type': 'text/plain' });
                    res.end('404 Not Found');
                    return;
                }
                res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
                res.end(data);
            });
            return;
        }

        const ext = path.extname(filePath).toLowerCase();
        const contentType = MIME_TYPES[ext] || 'application/octet-stream';

        fs.readFile(filePath, (readErr, content) => {
            if (readErr) {
                res.writeHead(500, { 'Content-Type': 'text/plain' });
                res.end('Server Error');
                return;
            }
            res.writeHead(200, { 'Content-Type': contentType });
            res.end(content);
        });
    });
});

